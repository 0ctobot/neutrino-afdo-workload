#!/bin/bash
# Generate the workload's assets (app/assets) with ffmpeg: images of mixed
# sizes and formats for the list, a local page for the WebView, and the media
# clips.  ffmpeg encoders are not guaranteed to be bit-exact across versions:
# MANIFEST records the ffmpeg version, the arguments and every file's sha256.
# Reproducibility rests on the released APK, which carries the assets.
set -euo pipefail
H=$(cd "$(dirname "$0")" && pwd)
A=$H/app/assets
rm -rf "$A" && mkdir -p "$A/images" "$A/web" "$A/media"
log=$(mktemp)
ff() { echo "ffmpeg $*" | sed "s|$A/||g" >> "$log"; ffmpeg -hide_banner -loglevel error -y "$@"; }

# Images: fractals, test patterns and noise (realistic entropy), 24 files.
i=0
for src in "mandelbrot=s=%s:maxiter=300" "testsrc2=s=%s" "cellauto=s=%s:rule=110" "life=s=%s:mold=10:ratio=0.3" \
           "gradients=s=%s:n=5" "mandelbrot=s=%s:start_scale=0.3"; do
	for size in 640x480 1080x1080 1600x1200 2400x1800; do
		i=$((i + 1))
		s=${src//%s/$size}
		if [ $((i % 3)) = 0 ]; then
			ff -f lavfi -i "$s" -vf "noise=alls=12:allf=t,format=yuv420p" -frames:v 1 -q:v 75 -c:v libwebp "$A/images/img$(printf %02d $i).webp"
		else
			ff -f lavfi -i "$s" -vf "noise=alls=12:allf=t,format=yuvj420p" -frames:v 1 -q:v $((2 + i % 6)) "$A/images/img$(printf %02d $i).jpg"
		fi
	done
done

# Local page for the WebView: long article text, images, CSS animation.
{
	echo '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">'
	echo '<style>body{font:17px/1.5 sans-serif;margin:16px}img{width:100%;height:auto;border-radius:8px}'
	echo '.spin{width:48px;height:48px;background:#58a;animation:r 1.2s linear infinite;margin:12px 0}'
	echo '@keyframes r{to{transform:rotate(360deg)}}table{border-collapse:collapse;width:100%}td{border:1px solid #ccc;padding:4px}</style>'
	echo '</head><body>'
	for s in $(seq 1 60); do
		echo "<h2>Section $s</h2><div class=spin></div>"
		for p in 1 2 3; do
			echo "<p>$(awk -v s=$((s * 7 + p)) 'BEGIN{srand(s); split("kernel scheduler page cache binder surface frame render buffer queue device memory reclaim fault vsync display codec network socket storage journal", w, " "); for (i = 0; i < 90; i++) printf "%s ", w[int(rand() * 21) + 1]}')</p>"
		done
		echo "<img src=\"../images/img$(printf %02d $(( (s % 24) + 1 ))).$([ $(( ((s % 24) + 1) % 3 )) = 0 ] && echo webp || echo jpg)\" loading=lazy>"
		echo "<table>$(for r in 1 2 3 4; do echo "<tr><td>$s.$r</td><td>$((s * r * 37 % 1000))</td><td>row $r</td></tr>"; done)</table>"
	done
	echo '</body></html>'
} > "$A/web/page.html"

# Media: HEVC 1080p60 (local), AV1 1080p30 (streamed), AAC and Opus audio.
# Test pattern plus moving noise, so the bitrate is realistic.
V="testsrc2=s=1920x1080:r=%d,noise=alls=10:allf=t+u,format=yuv420p"
ff -f lavfi -i "$(printf "$V" 60)" -t 20 -c:v libx265 -preset medium -x265-params log-level=error:keyint=120 \
	-b:v 12M -tag:v hvc1 -an -movflags +faststart "$A/media/hevc-1080p60.mp4"
ff -f lavfi -i "$(printf "$V" 30)" -t 20 -c:v libsvtav1 -preset 8 -b:v 4M -g 60 -an -movflags +faststart "$A/media/av1-1080p30.mp4"
ff -f lavfi -i "sine=frequency=440:duration=120" -f lavfi -i "sine=frequency=554:duration=120" \
	-filter_complex "amerge=inputs=2,volume=0.5" -ac 2 -c:a aac -b:a 160k "$A/media/tone.m4a"
ff -f lavfi -i "sine=frequency=330:duration=120" -f lavfi -i "anoisesrc=d=120:c=pink:a=0.05" \
	-filter_complex "amix=inputs=2" -ac 2 -c:a libopus -b:a 128k "$A/media/tone.opus"

{
	echo "# generated by assets.sh on $(date -u +%FT%TZ)"
	echo "ffmpeg: $(ffmpeg -hide_banner -version | head -1)"
	sed 's/^/command: /' "$log"
	(cd "$A" && find . -type f ! -name MANIFEST | sort | xargs sha256sum)
} > "$A/MANIFEST"
rm -f "$log"
du -sh "$A"
